declare(strict_types=1);

namespace Berlioz\DocParser\Treatment;

use Berlioz\DocParser\Doc\Documentation;
use Berlioz\DocParser\Doc\File\Page;
use Berlioz\HtmlSelector\Exception\HtmlSelectorException;
use Berlioz\HtmlSelector\HtmlSelector;

/**
 * Class AnchorTreatment.
 *
 * Resolves the fragments of internal links written with GitHub-style anchors (flat slug of the heading)
 * to the ids of the headings of the target page, which are hierarchical when generated by PageSummaryTreatment.
 * Must run after the ids of the headings are defined.
 */
class AnchorTreatment implements TreatmentInterface
{
    private HtmlSelector $htmlSelector;
    /** @var array<string, array{ids: array<string, true>, slugs: array<string, string>}> Anchors by page path */
    private array $anchors = [];

    public function __construct()
    {
        $this->htmlSelector = new HtmlSelector();
    }

    /**
     * @inheritDoc
     * @throws HtmlSelectorException
     */
    public function handle(Documentation $documentation): void
    {
        $this->anchors = [];

        /** @var Page $page */
        foreach ($documentation->getFiles()->filter(fn($file) => $file instanceof Page) as $page) {
            $this->doAnchorTreatment($page, $documentation);
        }

        $this->anchors = [];
    }

    /**
     * Do anchor treatment.
     *
     * @param Page $page
     * @param Documentation $documentation
     *
     * @throws HtmlSelectorException
     */
    public function doAnchorTreatment(Page $page, Documentation $documentation): void
    {
        $contents = $page->getContents();

        // No link with fragment in page
        if (!str_contains($contents, '#')) {
            return;
        }

        $query = $this->htmlSelector->query($contents);
        $modified = false;

        foreach ($query->find('a[href]') as $link) {
            $href = (string)$link->attr('href');
            $resolved = $this->getHrefResolved($href, $page, $documentation);

            if ($resolved === $href) {
                continue;
            }

            $link->attr('href', $resolved);
            $modified = true;
        }

        if (true === $modified) {
            $page->setContents($query->find('html > body')->html());
        }
    }

    /**
     * Get href with its fragment resolved.
     *
     * The href is returned unchanged if it has no fragment, if it is not a link to a page of the documentation,
     * if its fragment is an existing id of the target page, or if no heading of the target page matches.
     *
     * @param string $href
     * @param Page $page
     * @param Documentation $documentation
     *
     * @return string
     * @throws HtmlSelectorException
     */
    public function getHrefResolved(string $href, Page $page, Documentation $documentation): string
    {
        if (!str_contains($href, '#')) {
            return $href;
        }

        $url = parse_url($href);

        if (false === $url || isset($url['scheme']) || isset($url['host'])) {
            return $href;
        }

        $fragment = rawurldecode($url['fragment'] ?? '');

        if ('' === $fragment) {
            return $href;
        }

        // Target page
        $targetPage = $page;
        if (isset($url['path'])) {
            $targetPath = b_resolve_absolute_path('/' . $page->getPath(), $url['path']);

            if (null === $targetPath) {
                return $href;
            }

            $targetPage = $documentation->getFiles()->findByPath($targetPath);
        }

        if (!$targetPage instanceof Page) {
            return $href;
        }

        $anchors = $this->getAnchors($targetPage);

        // Fragment is an id of the target page, or is unknown
        if (isset($anchors['ids'][$fragment]) || !isset($anchors['slugs'][$fragment])) {
            return $href;
        }

        return explode('#', $href, 2)[0] . '#' . rawurlencode($anchors['slugs'][$fragment]);
    }

    /**
     * Get anchors of a page.
     *
     * @param Page $page
     *
     * @return array{ids: array<string, true>, slugs: array<string, string>} Ids of the page, and ids of headings
     *                                                                         by GitHub-style slug
     * @throws HtmlSelectorException
     */
    private function getAnchors(Page $page): array
    {
        if (isset($this->anchors[$path = $page->getPath()])) {
            return $this->anchors[$path];
        }

        $anchors = ['ids' => [], 'slugs' => []];
        $query = $this->htmlSelector->query($page->getContents());

        foreach ($query->find('[id]') as $element) {
            $anchors['ids'][(string)$element->attr('id')] = true;
        }

        // Same deduplication as GitHub: the first heading gets the slug, the next ones a numeric suffix
        $occurrences = [];
        foreach ($query->find(':header') as $header) {
            $slug = $original = $this->slugify($header->text());

            while (isset($occurrences[$slug])) {
                $occurrences[$original]++;
                $slug = $original . '-' . $occurrences[$original];
            }
            $occurrences[$slug] = 0;

            if (null !== ($id = $header->attr('id')) && '' !== $id) {
                $anchors['slugs'][$slug] = (string)$id;
            }
        }

        return $this->anchors[$path] = $anchors;
    }

    /**
     * Slugify the text of a heading like GitHub does.
     *
     * Lower case; letters, numbers, hyphens, underscores and spaces are kept; spaces are replaced with hyphens.
     *
     * @param string $str
     *
     * @return string
     */
    private function slugify(string $str): string
    {
        $slug = preg_replace('/[^\p{L}\p{M}\p{N}\p{Pc}\- ]/u', '', mb_strtolower(trim($str)));

        return str_replace(' ', '-', $slug ?? '');
    }
}
